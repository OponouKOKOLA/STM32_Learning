void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART2)
  {
    if (bouton_led == '1')
    {
      mode_clignotement = 0;
      BSP_LED_On(LED2);
    }
    else if (bouton_led == '2')
    {
      mode_clignotement = 0;
      BSP_LED_Off(LED2);
    }
    else if (bouton_led == '3')
    {
      mode_clignotement = 1;
    }

    HAL_UART_Receive_IT(&huart2, &bouton_led, 1);
  }
}
